use crate::{qudt_unit_name::QudtUnitName, qudt_vocabulary::QudtVocabulary, unit_notations::UnitNotations};
use sha2::{Digest, Sha256};
use std::collections::BTreeSet;

/// The Rust source of the QUDT unit table of `vocabulary`, generated from the vocabulary file `turtle`.
///
/// Each unit takes one line, so a new release shows in a diff unit by unit; the table is therefore kept
/// out of rustfmt's reach.
pub fn rust_source(vocabulary: &QudtVocabulary, turtle: &[u8]) -> String {
    let digest = hex::encode(Sha256::digest(turtle));
    let entries: Vec<String> = vocabulary.units().map(|(unit, notations)| entry(unit, notations)).collect();
    let release = &vocabulary.release;
    let count = entries.len();

    let header = format!(
        "\
// @generated by cassiopeia-unit-notation-generator from the QUDT unit vocabulary, release {release}
// (`VOCAB_QUDT-UNITS-ALL.ttl`, SHA-256 {digest}).
// Do not edit: run `cargo run -p cassiopeia-unit-notation-generator -- generate <path to VOCAB_QUDT-UNITS-ALL.ttl>`.
//
// QUDT, Quantities, Units, Dimensions and Types, by QUDT.org (https://qudt.org), release {release}, licensed
// under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Only units that carry a
// `qudt:uneceCommonCode` are kept, with their codes, symbols, and English labels. The `qudt:ucumCode` values
// are UCUM codes, copyright Regenstrief Institute, Inc., used under the UCUM License, which disclaims all
// warranties (https://ucum.org/license).

use crate::qudt::qudt_unit::QudtUnit;
use cefact_units::UnitCode;

/// Every unit of QUDT release {release} that carries a `qudt:uneceCommonCode` Recommendation No. 20 lists, in
/// order of local name.
#[rustfmt::skip]
pub(crate) static QUDT_UNITS: [QudtUnit; {count}] = [
"
    );
    let mut source = header;
    for line in entries {
        source.push_str(&line);
    }
    source.push_str("];\n");
    source
}

/// The table line of `unit`.
fn entry(unit: &QudtUnitName, notations: &UnitNotations) -> String {
    let codes: Vec<String> = notations.codes.iter().map(|code| format!("UnitCode::{code:?}")).collect();
    format!(
        "    QudtUnit {{ id: {id:?}, codes: &[{codes}], symbols: &[{symbols}], labels: &[{labels}] }},\n",
        id = unit.as_str(),
        codes = codes.join(", "),
        symbols = literals(&notations.symbols),
        labels = literals(&notations.labels),
    )
}

/// `texts` as a comma-separated list of Rust string literals.
fn literals(texts: &BTreeSet<String>) -> String {
    texts.iter().map(|text| format!("{text:?}")).collect::<Vec<_>>().join(", ")
}

#[cfg(test)]
mod tests {
    use crate::{qudt_vocabulary::QudtVocabulary, rust_source::rust_source};

    const VOCABULARY: &str = r#"
        @prefix owl: <http://www.w3.org/2002/07/owl#> .
        @prefix qudt: <http://qudt.org/schema/qudt/> .
        @prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
        @prefix unit: <http://qudt.org/vocab/unit/> .

        <http://qudt.org/3.5.3/vocab/unit> owl:versionIRI <http://qudt.org/3.5.3/vocab/unit> .
        unit:DEG_C qudt:symbol "°C" ; qudt:ucumCode "Cel" ; qudt:uneceCommonCode "CEL" ; rdfs:label "Degree \"Celsius\""@en .
    "#;

    #[test]
    fn each_unit_is_one_line_of_escaped_literals() {
        let vocabulary = QudtVocabulary::parse(VOCABULARY.as_bytes()).unwrap();
        let source = rust_source(&vocabulary, VOCABULARY.as_bytes());

        assert!(
            source.contains("    QudtUnit { id: \"DEG_C\", codes: &[UnitCode::Cel], symbols: &[\"Cel\", \"°C\"], labels: &[\"Degree \\\"Celsius\\\"\"] },\n")
        );
        assert!(source.contains("pub(crate) static QUDT_UNITS: [QudtUnit; 1] = [\n"));
        assert!(source.contains("release 3.5.3"));
        assert!(source.ends_with("];\n"));
    }
}
